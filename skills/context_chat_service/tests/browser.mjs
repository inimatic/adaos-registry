import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';
const require=createRequire(path.resolve('e2e/stand/browser/package.json'));
const {chromium}=require('playwright');
const expect=require('@playwright/test').expect.configure({timeout:45000});
const token=process.env.ADAOS_REVIEW_TOKEN || process.env.ADAOS_E2E_HUB_TOKEN;
if (!token) throw new Error('Local AdaOS runtime credential is required');
const hub=process.env.ADAOS_E2E_HUB_URL || 'http://127.0.0.1:8777';
const prefix='/api/services/context_chat_service/ui/';
const out=path.resolve(process.env.ADAOS_E2E_OUTPUT || 'e2e/artifacts/context-chat/browser');
await fs.mkdir(out,{recursive:true});
const report={checks:[],errors:[],abortedRequests:[],responses:[],passed:false}, created=[];
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:960},locale:'ru-RU'});
const page=await context.newPage();
page.setDefaultTimeout(45000);
page.on('pageerror',error=>report.errors.push(error.message));
page.on('requestfailed',request=>{
  const url=new URL(request.url());if(!url.pathname.includes('/ui/api/'))return;
  const failure=request.failure()?.errorText;
  // Navigation and explicit reload cancel the old page's outstanding polls.
  if(failure==='net::ERR_ABORTED')report.abortedRequests.push(url.pathname);
  else report.errors.push('Request failed: '+url.pathname+' '+failure);
});
page.on('response',response=>{const url=new URL(response.url());if(url.pathname.includes('/ui/api/'))report.responses.push({path:url.pathname,method:response.request().method(),status:response.status()});});
page.on('dialog',dialog=>dialog.accept());
const check=name=>{report.checks.push(name);console.log(name);};
const request=async(method,route,data)=>{
  const response=await context.request.fetch(hub+prefix+'api/'+route,{method,data});
  if(!response.ok()) throw new Error(`Application request failed: ${method} ${route} (${response.status()})`);
  return response.json();
};
try {
  await page.goto(hub+'/api/services/context_chat_service/ui-bootstrap?token='+encodeURIComponent(token),{waitUntil:'networkidle',timeout:60000});
  await expect(page.locator('#new-project')).toBeVisible();
  await expect(page.locator('#account-label')).toHaveText('ChatGPT не подключён');
  await expect(page.locator('#send')).toBeDisabled();
  await expect(page.locator('#model option')).toHaveCount(1);
  check('disconnected_state_has_no_fake_models_or_answers');
  await page.screenshot({path:path.join(out,'desktop-empty.png'),fullPage:true});
  await page.locator('#new-project').click();
  await page.locator('#project-name').fill('[Проверка] Личное общение');
  await page.locator('#project-description').fill('Проверка изоляции контекста');
  await page.locator('#initial-context').fill('Предпочитаю короткие ответы. Мы договорились обсуждать задачи по пятницам.');
  const firstCreated=page.waitForResponse(response=>response.url().endsWith('/api/projects')&&response.request().method()==='POST');
  await page.locator('#project-form button[type=submit]').click();
  const first=await (await firstCreated).json();created.push(first.id);
  await expect(page.locator('#project-title')).toHaveText('[Проверка] Личное общение');
  let rows=(await request('GET','state')).projects;
  await page.locator('#context-toggle').click();
  await expect(page.locator('#context-content')).toContainText('Начальный контекст');
  check('project_creation_imports_initial_context');
  await page.locator('#files').setInputFiles({name:'preferences.txt',mimeType:'text/plain',buffer:Buffer.from('Пользователь предпочитает русский язык и ясные формулировки.','utf8')});
  await expect(page.locator('#draft-files')).toContainText('preferences.txt');
  await expect(page.locator('#context-content')).toContainText('preferences.txt');
  await page.locator('[data-remove-file]').click();
  await expect(page.locator('#draft-files')).not.toContainText('preferences.txt');
  check('document_upload_and_removal_before_sending');
  await page.locator('#memory-tab').click();
  await page.locator('#edit-memory').click();
  await page.locator('#memory-summary').fill('Начали обсуждение личных задач.');
  await page.locator('#memory-preferences').fill('Кратко, на русском языке.');
  await page.locator('#memory-form button[type=submit]').click();
  await expect(page.locator('#context-content')).toContainText('Кратко, на русском языке.');
  await page.reload({waitUntil:'networkidle'});
  await expect(page.locator('#project-title')).toHaveText('[Проверка] Личное общение');
  check('editable_memory_and_selected_project_persist_after_reload');
  await page.locator('#new-project').click();
  await page.locator('#project-name').fill('[Проверка] Второй проект');
  const secondCreated=page.waitForResponse(response=>response.url().endsWith('/api/projects')&&response.request().method()==='POST');
  await page.locator('#project-form button[type=submit]').click();
  const second=await (await secondCreated).json();created.push(second.id);
  await expect(page.locator('#project-title')).toHaveText('[Проверка] Второй проект');
  rows=(await request('GET','state')).projects;
  const secondState=await request('GET','projects/'+second.id);
  expect(secondState.sources).toHaveLength(0);expect(secondState.messages).toHaveLength(0);expect(secondState.project.memory).toEqual({});
  check('projects_do_not_share_sources_memory_or_messages');
  await page.locator('#edit-project').click();
  await page.locator('#project-name').fill('[Проверка] Переименованный');
  await page.locator('#project-form button[type=submit]').click();
  await expect(page.locator('#project-title')).toHaveText('[Проверка] Переименованный');
  await page.locator('#search').fill('Переименованный');
  await expect(page.locator('[data-project]')).toHaveCount(1);
  await page.locator('#search').fill('');
  check('project_rename_and_search');
  await page.locator(`[data-project="${first.id}"]`).click();
  await expect(page.locator('#project-title')).toHaveText('[Проверка] Личное общение');
  await page.locator('#draft').fill('Несохранённый текст только первого проекта');
  await page.locator(`[data-project="${second.id}"]`).click();
  await expect(page.locator('#draft')).toHaveValue('');
  await page.locator(`[data-project="${first.id}"]`).click();
  await expect(page.locator('#draft')).toHaveValue('Несохранённый текст только первого проекта');
  check('drafts_remain_scoped_to_each_project');
  await page.reload({waitUntil:'networkidle'});
  await expect(page.locator('#draft')).toHaveValue('Несохранённый текст только первого проекта');
  check('draft_survives_interface_session_reload');
  await page.locator('#edit-project').click();
  const downloaded=page.waitForEvent('download');
  await page.locator('#export-project').click();
  const download=await downloaded;
  const exported=JSON.parse(await fs.readFile(await download.path(),'utf8'));
  expect(exported.schema).toBe('context_chat.project.v1');
  expect(exported.project.id).toBe(first.id);
  expect(exported.project.memory.preferences).toBe('Кратко, на русском языке.');
  expect(exported.sources[0].content).toContain('Предпочитаю короткие ответы');
  expect(JSON.stringify(exported)).not.toContain(second.id);
  await page.locator('#close-modal').click();
  check('project_export_contains_history_context_and_memory_only_for_selected_project');
  if(!(await page.locator('#context-panel').isVisible()))await page.locator('#context-toggle').click();
  await page.locator('#sources-tab').click();
  await page.locator('[data-delete-source]').click();
  await page.locator('#memory-tab').click();
  await expect(page.locator('#context-content')).not.toContainText('Кратко, на русском языке.');
  check('source_deletion_invalidates_derived_memory');
  await page.screenshot({path:path.join(out,'desktop-project.png'),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await page.locator('#account-button').click();
  await expect(page.locator('#modal-body')).toContainText('История чатов и память аккаунта автоматически не загружаются');
  await expect(page.locator('#connect')).toBeVisible();
  await page.screenshot({path:path.join(out,'account-disconnected.png'),fullPage:true});
  await page.locator('#close-modal').click();
  check('personal_account_connection_is_explicit_and_secret_free');
  await page.setViewportSize({width:390,height:844});
  if(await page.locator('#context-panel').isVisible())await page.locator('#close-context').click();
  await page.locator('#open-projects').click();
  await expect(page.locator('#sidebar')).toHaveClass(/open/);
  await page.locator(`[data-project="${second.id}"]`).click();
  await expect(page.locator('#project-title')).toHaveText('[Проверка] Переименованный');
  await page.locator('#context-toggle').click();
  await expect(page.locator('#context-panel')).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await page.screenshot({path:path.join(out,'mobile-context.png'),fullPage:true});
  check('mobile_projects_drawer_and_context_without_horizontal_overflow');
  await page.locator('#close-context').click();
  await page.locator('#edit-project').click();
  await page.locator('#delete-project').click();
  await expect(page.locator('#project-title')).toHaveText('Context Chat');
  check('confirmed_project_deletion');
  const anonymous=await browser.newContext();
  const denied=await anonymous.request.get(hub+prefix+'api/state');
  expect([401,403]).toContain(denied.status());
  await anonymous.close();
  check('unauthenticated_gateway_cannot_read_project_data');
  report.passed=report.errors.length===0;
} catch(error) {
  report.errors.push(String(error.message).replaceAll(token,'<redacted>').replaceAll(encodeURIComponent(token),'<redacted>'));
  await page.screenshot({path:path.join(out,'failure.png'),fullPage:true}).catch(()=>{});
} finally {
  for(const id of created)await context.request.delete(hub+prefix+'api/projects/'+id+'?confirmed=true').catch(()=>{});
  await fs.writeFile(path.join(out,'report.json'),JSON.stringify(report,null,2),'utf8');
  console.log(JSON.stringify({passed:report.passed,checks:report.checks,errors:report.errors,response_count:report.responses.length},null,2));
  await browser.close();
}
if(!report.passed)process.exitCode=1;
